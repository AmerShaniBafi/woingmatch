CREATE TABLE preferences (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             user_id BIGINT NOT NULL UNIQUE,

                             max_rent NUMERIC(10, 2) NOT NULL,
                             preferred_location VARCHAR(255) NOT NULL,
                             min_bedrooms INTEGER NOT NULL,
                             min_area INTEGER NOT NULL,
                             energy_label VARCHAR(10) NOT NULL,
                             parking_required BOOLEAN NOT NULL,
                             balcony_required BOOLEAN NOT NULL,

                             max_rent_weight INTEGER NOT NULL,
                             location_weight INTEGER NOT NULL,
                             bedrooms_weight INTEGER NOT NULL,
                             area_weight INTEGER NOT NULL,
                             energy_label_weight INTEGER NOT NULL,
                             parking_weight INTEGER NOT NULL,
                             balcony_weight INTEGER NOT NULL,

                             CONSTRAINT fk_preferences_user
                                 FOREIGN KEY (user_id)
                                     REFERENCES users(id)
                                     ON DELETE CASCADE,

                             CONSTRAINT chk_max_rent CHECK (max_rent > 0),
                             CONSTRAINT chk_min_bedrooms CHECK (min_bedrooms >= 0),
                             CONSTRAINT chk_min_area CHECK (min_area > 0),

                             CONSTRAINT chk_weights_range CHECK (
                                 max_rent_weight BETWEEN 0 AND 100
                                     AND location_weight BETWEEN 0 AND 100
                                     AND bedrooms_weight BETWEEN 0 AND 100
                                     AND area_weight BETWEEN 0 AND 100
                                     AND energy_label_weight BETWEEN 0 AND 100
                                     AND parking_weight BETWEEN 0 AND 100
                                     AND balcony_weight BETWEEN 0 AND 100
                                 ),

                             CONSTRAINT chk_total_weight CHECK (
                                 max_rent_weight
                                     + location_weight
                                     + bedrooms_weight
                                     + area_weight
                                     + energy_label_weight
                                     + parking_weight
                                     + balcony_weight = 100
                                 )
);